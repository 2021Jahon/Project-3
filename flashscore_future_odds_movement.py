def build_target_dates(now_date: date) -> tuple[set[date], date, date]:
    if SPECIFIC_DATES:
        parsed_dates = {
            datetime.strptime(d.strip(), "%d.%m.%Y").date() for d in SPECIFIC_DATES
        }
        return parsed_dates, min(parsed_dates), max(parsed_dates)

    start_dt = (
        datetime.strptime(START_DATE.strip(), "%d.%m.%Y").date()
        if START_DATE
        else now_date
    )
    end_dt = start_dt + timedelta(days=DAYS_AHEAD)
    target_dates = {start_dt + timedelta(days=i) for i in range(DAYS_AHEAD + 1)}
    return target_dates, start_dt, end_dt


def resolve_run_mode() -> str:
    cli_args = {arg.strip().lower() for arg in sys.argv[1:]}
    if "--refresh" in cli_args or "-r" in cli_args:
        return "REFRESH"
    if "--full" in cli_args or "-f" in cli_args:
        return "FULL"

    cfg_mode = RUN_MODE.strip().upper()
    if cfg_mode == "REFRESH":
        if os.path.exists(OUTPUT_EXCEL):
            return "REFRESH"
        logger.warning(
            f"⚠️ Файл {OUTPUT_EXCEL} еще не существует — переключаюсь в режим FULL."
        )
        return "FULL"
    return "FULL"


