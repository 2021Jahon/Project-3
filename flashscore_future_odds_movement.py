    @staticmethod
    def _to_float(raw: Any) -> Optional[float]:
        if raw is None:
            return None
        try:
            val = float(str(raw).replace(",", "."))
            return round(val, 2) if val > 1.0 else None
        except ValueError:
            return None

    @classmethod
    def _extract_odd_pair(cls, item: dict[str, Any]) -> tuple[Optional[float], Optional[float]]:
        open_val = cls._to_float(item.get("opening"))
        curr_val = cls._to_float(item.get("value"))

        if open_val is None and curr_val is not None:
            open_val = curr_val
        elif curr_val is None and open_val is not None:
            curr_val = open_val

        return open_val, curr_val

    @staticmethod
    def _bookmaker_sort_key(entry: dict[str, Any]) -> int:
        bm_id = entry.get("bookmakerId")
        if bm_id is None:
            return 999
        try:
            bm_int = int(str(bm_id))
            if bm_int in PREFERRED_BOOKMAKERS:
                return PREFERRED_BOOKMAKERS.index(bm_int)
        except (TypeError, ValueError):
            pass
        return 999

    @staticmethod
    def _normalize_handicap(hcp: Any) -> str:
        raw = hcp.get("value") if isinstance(hcp, dict) else hcp
        if raw is None:
            return ""
        try:
            val = float(str(raw).replace(",", "."))
            return f"{val:g}"
        except ValueError:
            return str(raw).strip()

    @staticmethod
    def _store_pair(
        target: dict[str, Any],
        market_name: str,
        pair: tuple[Optional[float], Optional[float]],
    ) -> None:
        open_val, curr_val = pair
        if open_val is not None:
            target[f"{market_name}__open"] = open_val
        if curr_val is not None:
            target[f"{market_name}__curr"] = curr_val

    def _parse_odds_response(self, data: dict[str, Any]) -> dict[str, Any]:
        parsed: dict[str, Any] = {}
        data_root = data.get("data")
        if not isinstance(data_root, dict):
            return parsed

        odds_block = (
            data_root.get("findOddsByEventId")
            or data_root.get("findPrematchOddsByEventId")
            or {}
        )
        if not isinstance(odds_block, dict):
            return parsed

        odds_list = odds_block.get("odds")
        if not isinstance(odds_list, list) or not odds_list:
            return parsed

        ft_entries: list[dict[str, Any]] = [
            e for e in odds_list
            if isinstance(e, dict) and e.get("bettingScope") in ("FULL_TIME", None)
        ]
        ft_entries.sort(key=self._bookmaker_sort_key)

        home_pid: Optional[str] = None
        away_pid: Optional[str] = None

        # 1. 1X2 (HOME_DRAW_AWAY -> П1, Х, П2)
        for entry in ft_entries:
            if entry.get("bettingType") != "HOME_DRAW_AWAY":
                continue
            items = [x for x in (entry.get("odds") or []) if isinstance(x, dict)]
            if len(items) < 3:
                continue

            non_null = [x for x in items if x.get("eventParticipantId") is not None]
            null_items = [x for x in items if x.get("eventParticipantId") is None]

            if len(non_null) == 2 and len(null_items) == 1:
                p1_pair = self._extract_odd_pair(non_null[0])
                p2_pair = self._extract_odd_pair(non_null[1])
                px_pair = self._extract_odd_pair(null_items[0])
                home_pid = str(non_null[0].get("eventParticipantId"))
                away_pid = str(non_null[1].get("eventParticipantId"))
            else:
                p1_pair = self._extract_odd_pair(items[0])
                px_pair = self._extract_odd_pair(items[1])
                p2_pair = self._extract_odd_pair(items[2])

            if p1_pair[1] and px_pair[1] and p2_pair[1]:
                self._store_pair(parsed, "П1", p1_pair)
                self._store_pair(parsed, "Х", px_pair)
                self._store_pair(parsed, "П2", p2_pair)
                break

        # 2. Двойной шанс (DOUBLE_CHANCE -> 1Х, 12, Х2)
        for entry in ft_entries:
            if entry.get("bettingType") != "DOUBLE_CHANCE":
                continue
            items = [x for x in (entry.get("odds") or []) if isinstance(x, dict)]
            if len(items) < 3:
                continue

            non_null = [x for x in items if x.get("eventParticipantId") is not None]
            null_items = [x for x in items if x.get("eventParticipantId") is None]

            if len(non_null) == 2 and len(null_items) == 1:
                if home_pid and away_pid:
                    item_1x = next(
                        (x for x in non_null if str(x.get("eventParticipantId")) == home_pid),
                        non_null[0],
                    )
                    item_x2 = next(
                        (x for x in non_null if str(x.get("eventParticipantId")) == away_pid),
                        non_null[1],
                    )
                else:
                    item_1x, item_x2 = non_null[0], non_null[1]
                pair_1x = self._extract_odd_pair(item_1x)
                pair_12 = self._extract_odd_pair(null_items[0])
                pair_x2 = self._extract_odd_pair(item_x2)
            else:
                pair_1x = self._extract_odd_pair(items[0])
                pair_12 = self._extract_odd_pair(items[1])
                pair_x2 = self._extract_odd_pair(items[2])

            if pair_1x[1] and pair_12[1] and pair_x2[1]:
                self._store_pair(parsed, "1Х", pair_1x)
                self._store_pair(parsed, "12", pair_12)
                self._store_pair(parsed, "Х2", pair_x2)
                break

        # 3. Тоталы (OVER_UNDER -> 1.5, 2.5, 3.5)
        target_totals = {
            "1.5": ("ТБ\n1,5", "ТМ\n1,5"),
            "2.5": ("ТБ\n2,5", "ТМ\n2,5"),
            "3.5": ("ТБ\n3,5", "ТМ\n3,5"),
        }
        for total_str, (col_over, col_under) in target_totals.items():
            for entry in ft_entries:
                if entry.get("bettingType") != "OVER_UNDER":
                    continue
                items = [x for x in (entry.get("odds") or []) if isinstance(x, dict)]
                matching = [
                    it for it in items
                    if self._normalize_handicap(it.get("handicap")) == total_str
                ]
                if len(matching) < 2:
                    continue

                over_pair: tuple[Optional[float], Optional[float]] = (None, None)
                under_pair: tuple[Optional[float], Optional[float]] = (None, None)

                for it in matching:
                    sel = str(it.get("selection") or it.get("overUnder") or "").upper()
                    if sel in ("OVER", "TRUE", "1"):
                        over_pair = self._extract_odd_pair(it)
                    elif sel in ("UNDER", "FALSE", "0"):
                        under_pair = self._extract_odd_pair(it)

                if over_pair[1] is None and under_pair[1] is None:
                    over_pair = self._extract_odd_pair(matching[0])
                    under_pair = self._extract_odd_pair(matching[1])

                if over_pair[1] and under_pair[1]:
                    self._store_pair(parsed, col_over, over_pair)
                    self._store_pair(parsed, col_under, under_pair)
                    break

        # 4. Обе забьют (BOTH_TEAMS_TO_SCORE -> ОЗ да, ОЗ нет)
        for entry in ft_entries:
            if entry.get("bettingType") != "BOTH_TEAMS_TO_SCORE":
                continue
            items = [x for x in (entry.get("odds") or []) if isinstance(x, dict)]
            if len(items) < 2:
                continue

            yes_pair: tuple[Optional[float], Optional[float]] = (None, None)
            no_pair: tuple[Optional[float], Optional[float]] = (None, None)
            for item in items:
                sel = str(item.get("selection") or item.get("bothTeamsToScore") or "").upper()
                if sel in ("YES", "TRUE", "1"):
                    yes_pair = self._extract_odd_pair(item)
                elif sel in ("NO", "FALSE", "0"):
                    no_pair = self._extract_odd_pair(item)

            if yes_pair[1] is None and no_pair[1] is None:
                yes_pair = self._extract_odd_pair(items[0])
                no_pair = self._extract_odd_pair(items[1])

            if yes_pair[1] and no_pair[1]:
                self._store_pair(parsed, "ОЗ да", yes_pair)
                self._store_pair(parsed, "ОЗ нет", no_pair)
                break

        return parsed

    def _apply_odds_update(
        self, match_id: str, odds_dict: dict[str, Any], is_refresh: bool
    ) -> None:
        target = self.matches.get(match_id)
        if not target:
            return

        for key, new_val in odds_dict.items():
            if key.endswith("__open") and is_refresh and PRESERVE_EXISTING_OPENING:
                existing_open = target.get(key, "")
                if isinstance(existing_open, (int, float)) and existing_open > 1.0:
                    continue
            target[key] = new_val

    async def fetch_match_odds(
        self,
        context: BrowserContext,
        match_id: str,
        sem: asyncio.Semaphore,
        is_refresh: bool = False,
    ) -> bool:
        async with sem:
            headers = {
                "Accept": "*/*",
                "X-Fsign": self.feed_sign,
                "Origin": self.base_domain,
                "Referer": f"{self.base_domain}/match/{match_id}/",
                "User-Agent": USER_AGENT,
            }
            merged_odds: dict[str, Any] = {}

            for prof in ODDS_QUERY_PROFILES:
                url = (
                    f"{ODDS_GRAPHQL_URL}?_hash=oce"
                    f"&eventId={match_id}"
                    f"&projectId={prof['projectId']}"
                    f"&geoIpCode={prof['geoIpCode']}"
                    f"&geoIpSubdivisionCode={prof['geoIpSubdivisionCode']}"
                )
                try:
                    resp = await context.request.get(url, headers=headers, timeout=10000)
                    if resp.status == 200:
                        data = await resp.json()
                        if isinstance(data, dict):
                            parsed = self._parse_odds_response(data)
                            for k, v in parsed.items():
                                if k not in merged_odds:
                                    merged_odds[k] = v
                            if "П1__curr" in merged_odds and "ТБ\n2,5__curr" in merged_odds:
                                break
                except Exception as e:
                    logger.debug(f"⚠️ Ошибка кэфов для {match_id} ({prof['geoIpCode']}): {e}")

            if merged_odds:
                self._apply_odds_update(match_id, merged_odds, is_refresh=is_refresh)
                await asyncio.sleep(random.uniform(0.04, 0.1))
                return True

            await asyncio.sleep(random.uniform(0.04, 0.1))
            return False


