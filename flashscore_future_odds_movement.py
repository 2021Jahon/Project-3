def _get_movement_fill(open_val: Any, curr_val: Any) -> Optional[PatternFill]:
    if not isinstance(open_val, (int, float)) or not isinstance(curr_val, (int, float)):
        return None
    if open_val <= 1.0 or curr_val <= 1.0:
        return None

    diff = curr_val - open_val
    if abs(diff) < 1e-4:
        return None

    if diff < 0:
        drop_pct = ((open_val - curr_val) / open_val) * 100.0
        return FILL_STRONG_DROP if drop_pct >= STRONG_DROP_PCT else FILL_LIGHT_DROP
    return FILL_RISE


def _build_sheet_dataframes(
    rows: list[dict[str, Any]], comp_columns: list[str], std_columns: list[str]
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    comp_rows: list[dict[str, Any]] = []
    curr_rows: list[dict[str, Any]] = []
    open_rows: list[dict[str, Any]] = []

    for r in rows:
        base_info = {col: r.get(col, "") for col in BASE_META_COLUMNS}
        c_row = dict(base_info)
        curr_r = dict(base_info)
        open_r = dict(base_info)

        for m in ODDS_MARKETS:
            o_val = r.get(f"{m}__open", "")
            v_val = r.get(f"{m}__curr", "")

            c_row[f"{m}\n(Старт)"] = o_val
            c_row[f"{m}\n(Тек)"] = v_val
            open_r[m] = o_val
            curr_r[m] = v_val

        comp_rows.append(c_row)
        curr_rows.append(curr_r)
        open_rows.append(open_r)

    df_comp = pd.DataFrame(comp_rows, columns=comp_columns) if comp_rows else pd.DataFrame(columns=comp_columns)
    df_curr = pd.DataFrame(curr_rows, columns=std_columns) if curr_rows else pd.DataFrame(columns=std_columns)
    df_open = pd.DataFrame(open_rows, columns=std_columns) if open_rows else pd.DataFrame(columns=std_columns)
    return df_comp, df_curr, df_open


def _format_comparison_sheet(
    ws: Worksheet,
    rows: list[dict[str, Any]],
    comp_columns: list[str],
    highlight_duplicates: bool = False,
) -> None:
    ws.row_dimensions[1].height = 32
    ws.freeze_panes = "F2"

    for i, col in enumerate(comp_columns, start=1):
        letter = get_column_letter(i)
        ws.column_dimensions[letter].width = BASE_WIDTHS.get(col, 9)
        header_cell = ws.cell(row=1, column=i)
        header_cell.font = Font(bold=True, size=10)
        header_cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        if "(Старт)" in col:
            header_cell.fill = FILL_HEADER_OPEN
        elif "(Тек)" in col:
            header_cell.fill = FILL_HEADER_CURR

    col_idx_map = {col: idx for idx, col in enumerate(comp_columns, start=1)}
    for row_idx, r in enumerate(rows, start=2):
        for col in ["DATE", "ID матча"]:
            c = ws.cell(row=row_idx, column=col_idx_map[col])
            c.alignment = Alignment(horizontal="center", vertical="center")

        if highlight_duplicates:
            if r.get("_dup_home"):
                ws.cell(row=row_idx, column=col_idx_map["HOME"]).fill = FILL_DUP_TEAM
            if r.get("_dup_away"):
                ws.cell(row=row_idx, column=col_idx_map["AWAY"]).fill = FILL_DUP_TEAM

        for m in ODDS_MARKETS:
            col_o = col_idx_map[f"{m}\n(Старт)"]
            col_c = col_idx_map[f"{m}\n(Тек)"]
            cell_o = ws.cell(row=row_idx, column=col_o)
            cell_c = ws.cell(row=row_idx, column=col_c)

            for cell in (cell_o, cell_c):
                cell.alignment = Alignment(horizontal="center", vertical="center")
                if isinstance(cell.value, (int, float)):
                    cell.number_format = "0.00"

            fill = _get_movement_fill(cell_o.value, cell_c.value)
            if fill:
                cell_c.fill = fill


