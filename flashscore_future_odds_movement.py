def split_unique_and_duplicates(
    sorted_rows: list[dict[str, Any]],
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    if not UNIQUE_TEAM_FILTER:
        return sorted_rows, []

    seen_teams: dict[str, set[str]] = defaultdict(set)
    unique_rows: list[dict[str, Any]] = []
    duplicate_rows: list[dict[str, Any]] = []

    for row in sorted_rows:
        league_key = (
            str(row.get("Лига", "")).strip().lower()
            if UNIQUE_SCOPE.upper() == "PER_LEAGUE"
            else "__global__"
        )
        home_norm = str(row.get("HOME", "")).strip().lower()
        away_norm = str(row.get("AWAY", "")).strip().lower()

        league_seen = seen_teams[league_key]
        home_is_dup = home_norm in league_seen
        away_is_dup = away_norm in league_seen

        row["_dup_home"] = home_is_dup
        row["_dup_away"] = away_is_dup

        league_seen.add(home_norm)
        league_seen.add(away_norm)

        if not home_is_dup and not away_is_dup:
            unique_rows.append(row)
        else:
            duplicate_rows.append(row)

    return unique_rows, duplicate_rows


def mark_duplicate_flags(
    unique_rows: list[dict[str, Any]], duplicate_rows: list[dict[str, Any]]
) -> None:
    seen_teams: dict[str, set[str]] = defaultdict(set)
    for r in unique_rows:
        l_key = (
            str(r.get("Лига", "")).strip().lower()
            if UNIQUE_SCOPE.upper() == "PER_LEAGUE"
            else "__global__"
        )
        seen_teams[l_key].add(str(r.get("HOME", "")).strip().lower())
        seen_teams[l_key].add(str(r.get("AWAY", "")).strip().lower())
        r["_dup_home"] = False
        r["_dup_away"] = False

    for r in duplicate_rows:
        l_key = (
            str(r.get("Лига", "")).strip().lower()
            if UNIQUE_SCOPE.upper() == "PER_LEAGUE"
            else "__global__"
        )
        h_norm = str(r.get("HOME", "")).strip().lower()
        a_norm = str(r.get("AWAY", "")).strip().lower()
        r["_dup_home"] = h_norm in seen_teams[l_key]
        r["_dup_away"] = a_norm in seen_teams[l_key]
        seen_teams[l_key].add(h_norm)
        seen_teams[l_key].add(a_norm)


