def _read_sheet_into_records(
    df_comp_or_std: Optional[pd.DataFrame],
    df_open_opt: Optional[pd.DataFrame],
    df_curr_opt: Optional[pd.DataFrame],
    tz: ZoneInfo,
) -> list[dict[str, Any]]:
    records: list[dict[str, Any]] = []
    if df_comp_or_std is None or df_comp_or_std.empty:
        return records

    open_lookup: dict[str, pd.Series] = {}
    curr_lookup: dict[str, pd.Series] = {}

    if df_open_opt is not None and not df_open_opt.empty and "ID матча" in df_open_opt.columns:
        for _, r in df_open_opt.iterrows():
            mid = str(r.get("ID матча", "")).strip()
            if mid:
                open_lookup[mid] = r

    if df_curr_opt is not None and not df_curr_opt.empty and "ID матча" in df_curr_opt.columns:
        for _, r in df_curr_opt.iterrows():
            mid = str(r.get("ID матча", "")).strip()
            if mid:
                curr_lookup[mid] = r

    for _, row in df_comp_or_std.iterrows():
        mid = str(row.get("ID матча", "")).strip()
        if not mid or mid.lower() == "nan":
            continue

        league = str(row.get("Лига", "")).strip()
        date_str = str(row.get("DATE", "")).strip()
        home = str(row.get("HOME", "")).strip()
        away = str(row.get("AWAY", "")).strip()

        item: dict[str, Any] = {
            "Лига": league,
            "DATE": date_str,
            "HOME": home,
            "AWAY": away,
            "ID матча": mid,
            "_sort_ts": _parse_date_to_ts(date_str, tz),
            "_dup_home": False,
            "_dup_away": False,
        }

        open_row = open_lookup.get(mid)
        curr_row = curr_lookup.get(mid)

        for m in ODDS_MARKETS:
            col_open_paired = f"{m}\n(Старт)"
            col_curr_paired = f"{m}\n(Тек)"

            o_val: Any = ""
            c_val: Any = ""

            if col_open_paired in df_comp_or_std.columns:
                o_val = _clean_excel_odd(row.get(col_open_paired))
            elif open_row is not None and m in open_row:
                o_val = _clean_excel_odd(open_row.get(m))
            elif m in df_comp_or_std.columns:
                o_val = _clean_excel_odd(row.get(m))

            if col_curr_paired in df_comp_or_std.columns:
                c_val = _clean_excel_odd(row.get(col_curr_paired))
            elif curr_row is not None and m in curr_row:
                c_val = _clean_excel_odd(curr_row.get(m))
            elif m in df_comp_or_std.columns:
                c_val = _clean_excel_odd(row.get(m))

            item[f"{m}__open"] = o_val
            item[f"{m}__curr"] = c_val

        records.append(item)

    return records


def load_existing_excel(
    path: str, tz: ZoneInfo, filter_mgr: ExactLeagueFilter
) -> tuple[dict[str, dict[str, Any]], list[dict[str, Any]], list[dict[str, Any]]]:
    filter_mgr.load_from_excel_files(path, EXTERNAL_FILTER_EXCEL)

    xl = pd.ExcelFile(path)
    sheet_names = [str(s) for s in xl.sheet_names]
    sheet_set = set(sheet_names)

    df_comp = xl.parse("Прогруз (Старт vs Тек)") if "Прогруз (Старт vs Тек)" in sheet_set else None
    df_curr = xl.parse("Текущие (Прогруз)") if "Текущие (Прогруз)" in sheet_set else None
    df_open = xl.parse("Стартовые (Opening)") if "Стартовые (Opening)" in sheet_set else None
    df_dup  = xl.parse("Дубликаты команд") if "Дубликаты команд" in sheet_set else None

    primary_df = df_comp if df_comp is not None else (df_open if df_open is not None else df_curr)
    if primary_df is None and sheet_names:
        primary_df = xl.parse(sheet_names[0])

    unique_rows = _read_sheet_into_records(primary_df, df_open, df_curr, tz)
    duplicate_rows = (
        _read_sheet_into_records(df_dup, None, None, tz)
        if df_dup is not None
        else []
    )

    # Применяем актуальный фильтр 0/1 даже в режиме REFRESH (если пользователь отключил лигу = 0)
    unique_rows = [r for r in unique_rows if filter_mgr.is_allowed(str(r.get("Лига", "")))]
    duplicate_rows = [r for r in duplicate_rows if filter_mgr.is_allowed(str(r.get("Лига", "")))]

    mark_duplicate_flags(unique_rows, duplicate_rows)

    matches_dict: dict[str, dict[str, Any]] = {}
    for r in unique_rows:
        matches_dict[str(r["ID матча"])] = r
        filter_mgr.match_counts[str(r["Лига"])] += 1
    for r in duplicate_rows:
        matches_dict[str(r["ID матча"])] = r
        filter_mgr.match_counts[str(r["Лига"])] += 1

    return matches_dict, unique_rows, duplicate_rows


